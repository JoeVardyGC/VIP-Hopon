/** Connect, create tables if needed. Call once before the server starts. */
export async function initDb() {
  // Online, never fall back to the built-in PGlite: it needs far more memory than a free server has
  // (Render's free plan runs out at 512 MB) and its data would vanish on every restart.
  if (!process.env.DATABASE_URL && process.env.NODE_ENV === 'production' && process.env.ALLOW_PGLITE !== 'true') {
    throw new Error('DATABASE_URL is not set. On Render: open the service > Environment > add DATABASE_URL with your Neon connection string, then Save (Render restarts by itself).');
  }
  if (process.env.DATABASE_URL) {
    if (!/^postgres(ql)?:\/\//.test(process.env.DATABASE_URL.trim())) {
      throw new Error('DATABASE_URL does not look like a PostgreSQL address. It should start with postgresql:// (copy it from Neon > Connect).');
    }
    const pg = (await import('pg')).default;
    // COUNT/SUM come back as 64-bit numbers; read them as JS numbers.
    pg.types.setTypeParser(20, (v: string) => parseInt(v, 10));
    pg.types.setTypeParser(1700, (v: string) => parseFloat(v));
    const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL, max: Number(process.env.PG_POOL || 5) });
    base = { query: (s, p) => pool.query(s, p as any[]) };
    runTx = async (fn) => {
      const c = await pool.connect();
      try {
        await c.query('BEGIN');
        const out = await fn({ query: (s, p) => c.query(s, p as any[]) });
        await c.query('COMMIT');
        return out;
      } catch (e) { await c.query('ROLLBACK').catch(() => {}); throw e; } finally { c.release(); }
    };
  } else {
    const { PGlite } = await import('@electric-sql/pglite');
    const name = process.env.HOPON_DB || 'pg';
    let dir: string | undefined;
    if (name !== 'memory') { dir = join(DATA_DIR, name); mkdirSync(DATA_DIR, { recursive: true }); }
    const db = await PGlite.create(dir, { parsers: { 20: (v: string) => parseInt(v, 10), 1700: (v: string) => parseFloat(v) } } as any);
    base = { query: (s, p) => db.query(s, p) as Promise<Result> };
    runTx = (fn) => db.transaction((t: any) => fn({ query: (s, p) => t.query(s, p) }));
  }
  for (const stmt of splitSql(SCHEMA)) await base.query(stmt, []);
}

/** Split the schema into statements, keeping $$ function bodies whole. */
function splitSql(sql: string) {
  const out: string[] = []; let cur = '', inFn = false;
  for (const line of sql.split('\n')) {
    if (line.trim().startsWith('--')) continue;
    cur += line + '\n';
    if ((line.match(/\$\$/g) || []).length % 2 === 1) inFn = !inFn;
    if (!inFn && line.trim().endsWith(';')) { if (cur.trim()) out.push(cur.trim()); cur = ''; }
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}

const q = (): Q => inTx.getStore() || base || (() => { throw new Error('Database not ready'); })();
/** Write SQL with ? placeholders; they become $1, $2 … for PostgreSQL. */
const conv = (sql: string) => { let i = 0; return sql.replace(/\?/g, () => `$${++i}`); };
const clean = (p: unknown[]) => p.map((v) => (v === undefined ? null : v));

export async function all<T = any>(sql: string, ...p: unknown[]): Promise<T[]> {
  return (await q().query(conv(sql), clean(p))).rows as T[];
}
export async function one<T = any>(sql: string, ...p: unknown[]): Promise<T | undefined> {
  return (await all<T>(sql, ...p))[0];
}
export async function run(sql: string, ...p: unknown[]) {
  const r = await q().query(conv(sql), clean(p));
  return { changes: r.rowCount ?? r.affectedRows ?? 0 };
}
/** INSERT … and get the new row's id back. */
export async function insert(sql: string, ...p: unknown[]): Promise<number> {
  const r = await q().query(conv(sql) + ' RETURNING id', clean(p));
  return Number(r.rows[0].id);
}
/** All queries inside fn run in one transaction (and nested calls join it). */
export async function tx<T>(fn: () => Promise<T>): Promise<T> {
  if (inTx.getStore()) return fn();
  return runTx((client) => inTx.run(client, fn));
}
